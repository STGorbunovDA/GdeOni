/**
 * D41. Слияние автоопределённого адреса с тем, что уже в поле.
 *
 * Задача: подставлять город по координатам, но НЕ затирать то, что юзер
 * вписал руками. Кладбище может называться «Москва», а по координатам
 * определится «городской округ Мытищи» — если молча перезаписать, человек
 * решит, что форма сломана.
 *
 * Правило: перезаписываем, только если поле пустое ИЛИ в нём лежит ровно
 * то, что мы сами подставили в прошлый раз (значит, юзер его не трогал).
 * Как только он отредактировал — поле его, и мы больше в него не лезем.
 */
export function mergeAutofilled(
  current: string,
  previousAuto: string,
  incoming: string | null,
): string {
  // Геокодер ничего не дал — оставляем как есть, пустое поле лучше вранья.
  if (!incoming) return current;

  const untouched = current.trim() === '' || current.trim() === previousAuto.trim();
  return untouched ? incoming : current;
}
