namespace GdeOni.Domain.Shared;

/// <summary>
/// Состояние обработки обращения. Open — никто ещё не взял в работу.
/// InProgress — админ принял в работу. Resolved — админ дал решение,
/// но точку ставит юзер: он либо подтверждает (AcceptResolution), либо
/// переоткрывает (Reopen). Closed — админ закрыл принудительно.
///
/// D40. Closed нужен именно потому, что Resolved НЕ терминален: юзер
/// может просто забыть подтвердить решение, и обращение висит в списке
/// вечно.
///
/// Терминальность Closed направлена на ЮЗЕРА: переоткрыть (Reopen) или
/// подтвердить (AcceptResolution) закрытое он не может. Админ же может
/// вернуть обращение в работу обычной сменой статуса — он мог закрыть по
/// ошибке, и запирать его в собственном решении незачем.
///
/// В БД хранится строкой (HasConversion&lt;string&gt;), поэтому новое
/// значение не требует миграции.
/// </summary>
public enum SupportTicketStatus
{
    Unknown = 0,
    Open = 1,
    InProgress = 2,
    Resolved = 3,
    Closed = 4
}
