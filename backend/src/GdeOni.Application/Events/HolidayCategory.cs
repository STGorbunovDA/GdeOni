    Orthodox = 2,

    /// <summary>Мусульманские праздники.</summary>
    Muslim = 3,

    /// <summary>Государственные праздники РФ.</summary>
    State = 4,

    /// <summary>
    /// Посты и постные дни (начало Великого / Петрова / Успенского /
